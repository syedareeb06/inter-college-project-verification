// Deploys ProjectConsortium to the local Hardhat node and seeds the same demo
// consortium (4 colleges) and sample projects as the web app. Usage (two terminals):
//   npx hardhat node
//   npx hardhat run scripts/deploy.js --network localhost
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

// The web app's own sample reports and crypto helpers, so both seed identical records.
const FRONTEND_JS = path.join(__dirname, "..", "..", "frontend", "js");
const Samples = require(path.join(FRONTEND_JS, "projectledger-samples.js"));
const PLCrypto = require(path.join(FRONTEND_JS, "projectledger-crypto.js"));

async function main() {
  const signers = await hre.ethers.getSigners();
  const [board] = signers;

  const consortium = await hre.ethers.deployContract("ProjectConsortium", [], board);
  await consortium.waitForDeployment();
  const address = await consortium.getAddress();
  console.log(`ProjectConsortium deployed to ${address} by the University Consortium Board ${board.address}`);

  for (const col of Samples.COLLEGES) {
    await (await consortium.addCollege(signers[col.account].address, col.name, col.code)).wait();
    console.log(`  admitted ${col.name.padEnd(36)} ${signers[col.account].address}`);
  }

  let id = 0;
  for (const step of Samples.SEED_PLAN) {
    const s = Samples.sample(step.key);
    const reg = await PLCrypto.buildRegistration({
      title: s.title,
      domain: s.domain,
      year: s.year,
      guide: s.guide,
      text: Samples.reportText(s),
      members: s.members.map(([name, roll]) => ({ name, roll })),
      salt: await PLCrypto.demoSalt(s.key),
    });
    await (await consortium.connect(signers[s.college]).registerProject(...reg.args)).wait();
    id += 1;
    for (const e of step.endorsers) await (await consortium.connect(signers[e]).endorseProject(id)).wait();
    console.log(`  project #${id} ${s.title.slice(0, 48).padEnd(48)} endorsements: ${1 + step.endorsers.length}`);
  }

  const { chainId } = await hre.ethers.provider.getNetwork();
  const out = path.join(__dirname, "..", "..", "frontend", "js", "local-deployment.js");
  fs.writeFileSync(
    out,
    `// AUTO-GENERATED by blockchain/scripts/deploy.js\nwindow.LOCAL_DEPLOYMENT = ${JSON.stringify({ address, chainId: Number(chainId) })};\n`
  );
  console.log(`Wrote ${path.relative(process.cwd(), out)} - open the web app and choose "Local Hardhat".`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
